import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
const out='tools/shots-rich-text'; fs.mkdirSync(out,{recursive:true});
const getEl=()=>page.evaluate(()=>{const s=window.__deckStore.getState(); return s.deck.slides[s.current].elements.find(e=>e.id==='s15-body');});
const root=page.locator('.text-edit');
const box=page.locator('.fit-inner [data-id="s15-body"]');
const open=async()=>{await box.dblclick({position:{x:150,y:20}}); await root.waitFor();};
const commit=async()=>{await page.keyboard.press('Control+Enter');await root.waitFor({state:'detached'});};
const measure=async(selector)=>page.locator(selector).evaluate(el=>Array.from(el.querySelectorAll('p, [data-run]')).map(n=>{
 const r=n.getBoundingClientRect(), s=getComputedStyle(n);
 return {text:n.textContent,x:r.x,y:r.y,w:r.width,h:r.height,color:s.color,size:s.fontSize,weight:s.fontWeight,align:s.textAlign};
}));
try {
 await page.goto('http://127.0.0.1:1420/?deck=/decks/neural-network/deck.json');
 await page.locator('.thumb').nth(14).click();
 const original=await getEl();
 const before=await measure('.fit-inner [data-id="s15-body"]');
 await page.screenshot({path:`${out}/before.png`});
 await open();
 assert.deepEqual(await measure('.text-edit'),before,'appearance stays identical');
 assert.equal(await root.evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
 await page.screenshot({path:`${out}/editing.png`});
 await commit(); assert.deepEqual(await getEl(),original,'no-op editing preserves model');
 console.log('PASS: exact text layout, mixed formatting and transparent background');
 await open(); await page.keyboard.press('Control+Home'); await page.keyboard.press('End'); await page.keyboard.insertText('追記😀');
 await commit();
 let edited=await getEl();
 assert(edited.paragraphs[0].runs.map(r=>r.text).join('').endsWith('追記😀'));
 assert.equal(edited.paragraphs[0].runs[0].color,original.paragraphs[0].runs[0].color);
 assert.equal(edited.paragraphs[0].runs[0].bold,true);
 console.log('PASS: text entry retains mixed formatting and emoji');
 await box.click({button:'right',position:{x:50,y:30}});
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).fill('28');
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).press('Enter');
 await page.getByRole('button',{name:'文字色 accent3',exact:true}).click();
 await page.screenshot({path:`${out}/context-menu.png`});
 await page.keyboard.press('Escape');
 edited=await getEl();
 assert.equal(edited.style.fontSize,28);
 assert(edited.paragraphs.every(p=>p.runs.every(r=>r.fontSize===28&&r.color==='accent3')));
 console.log('PASS: right-click changes entire text, including existing run overrides');
 await open();
 await page.keyboard.press('Control+Home');
 await page.keyboard.down('Shift'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight'); await page.keyboard.up('Shift');
 const selected=await page.evaluate(()=>getSelection().toString()); assert.equal(selected,'部品');
 // A real right-click inside the selected text should keep that selection.
 await root.click({button:'right',position:{x:8,y:12}});
 assert.equal(await page.locator('.format-caption').textContent(),'選択した文字');
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).fill('36');
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).press('Enter');
 await page.getByRole('button',{name:'文字色 accent2',exact:true}).click();
 await page.keyboard.press('Escape');
 await commit(); edited=await getEl();
 assert.equal(edited.paragraphs[0].runs[0].text,'部品');
 assert.equal(edited.paragraphs[0].runs[0].fontSize,36);
 assert.equal(edited.paragraphs[0].runs[0].color,'accent2');
 assert.equal(edited.paragraphs[0].runs[1].fontSize,28);
 assert.equal(edited.paragraphs[0].runs[1].color,'accent3');
 console.log('PASS: selection-only size and color survive multiple menu interactions');
 await open(); await page.keyboard.press('Control+End'); await page.keyboard.press('Enter'); await page.keyboard.insertText('新しい段落'); await commit();
 edited=await getEl();
 assert.equal(edited.paragraphs.length,original.paragraphs.length+1);
 assert.equal(edited.paragraphs.at(-1).runs.map(r=>r.text).join(''),'新しい段落');
 console.log('PASS: Enter creates a paragraph without losing text');
 await open(); await page.keyboard.press('Control+End'); await page.keyboard.insertText('取り消し'); await page.keyboard.press('Control+z'); await commit();
 assert.deepEqual(await getEl(),edited,'in-editor undo');
 await open(); await page.keyboard.insertText('キャンセル'); await page.keyboard.press('Escape');
 assert.deepEqual(await getEl(),edited,'Escape cancels');
 console.log('PASS: undo and Escape');
 await open(); await page.keyboard.press('Control+Home');
 await root.click({button:'right',position:{x:8,y:12}});
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).fill('31');
 await page.getByRole('spinbutton',{name:'文字サイズ',exact:true}).press('Enter');
 await page.getByLabel('文字色',{exact:true}).fill('#445566');
 await page.keyboard.press('Escape'); await commit();
 edited=await getEl();
 assert.equal(edited.style.fontSize,31); assert.equal(edited.style.color,'445566');
 assert(edited.paragraphs.every(p=>p.runs.every(r=>r.fontSize===31 && r.color==='445566')));
 console.log('PASS: whole-text formatting during editing updates base style and custom color');
 assert.deepEqual(errors,[]);
} finally { await browser.close(); }

